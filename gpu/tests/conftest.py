"""Shared pytest fixtures for the GS2 JAX port.

Reference data lives in ``gpu/refdata/<case>/`` (generated by
``gpu/scripts/make_refdata.sh``, gitignored):

* ``<case>.gs2export.nc``  coefficients, grids and the t = 0 state;
* ``<case>.gs2trace.nc``   per-probe stage dumps of the first steps;
* ``<case>.out.nc``        GS2's own output of the full run.

Tests that need a case skip (not fail) when its reference data is missing.
"""

from __future__ import annotations

import os
from functools import lru_cache
from pathlib import Path

import numpy as np
import pytest

import gs2gpu  # noqa: F401  (enables x64)
from gs2gpu.io.export import load_export
from gs2gpu.io.trace import Trace
from gs2gpu.numerics import max_abs_rel

GPU_DIR = Path(__file__).resolve().parents[1]
REFDATA = Path(os.environ.get("GS2GPU_REFDATA", GPU_DIR / "refdata"))
CASES_DIR = GPU_DIR / "cases"

# Tolerances from gpu/spec/00_decisions.md D1.
RTOL_KERNEL = 1e-12
RTOL_STEP = 1e-12


def all_cases() -> list[str]:
    return sorted(p.stem for p in CASES_DIR.glob("*.in"))


def case_dir(case: str) -> Path:
    return REFDATA / case


def _file(case: str, suffix: str) -> Path:
    return case_dir(case) / f"{case}{suffix}"


def have(case: str, what: str = "export") -> bool:
    suffix = {"export": ".gs2export.nc", "trace": ".gs2trace.nc", "out": ".out.nc"}[what]
    return _file(case, suffix).exists()


@lru_cache(maxsize=8)
def export_of(case: str):
    path = _file(case, ".gs2export.nc")
    if not path.exists():
        pytest.skip(f"no reference export for {case} (run gpu/scripts/make_refdata.sh)")
    return load_export(path)


@lru_cache(maxsize=8)
def trace_of(case: str) -> Trace:
    path = _file(case, ".gs2trace.nc")
    if not path.exists():
        pytest.skip(f"no reference trace for {case} (run gpu/scripts/make_refdata.sh)")
    return Trace(path)


def out_of(case: str) -> Path:
    path = _file(case, ".out.nc")
    if not path.exists():
        pytest.skip(f"no GS2 output for {case} (run gpu/scripts/make_refdata.sh)")
    return path


def cases_where(predicate) -> list[str]:
    """Cases with reference data for which ``predicate(export)`` is true.

    Used to parametrize tests over the feature matrix; evaluated at collection
    time, so only cheap checks belong in ``predicate``.
    """
    out = []
    for case in all_cases():
        if not have(case):
            continue
        try:
            if predicate(export_of(case)):
                out.append(case)
        except Exception:  # pragma: no cover - a broken export shows up in test_io
            out.append(case)
    return out or ["<no-refdata>"]


def assert_close(ref, got, rtol: float = RTOL_KERNEL, what: str = ""):
    """Max-abs-relative comparison (00_decisions.md D1)."""
    ref = np.asarray(ref)
    got = np.asarray(got)
    assert ref.shape == got.shape, f"{what}: shape {got.shape} != reference {ref.shape}"
    err = max_abs_rel(ref, got)
    assert err <= rtol, f"{what}: max-abs-relative error {err:.3e} > {rtol:.1e}"
    return err


@pytest.fixture(params=all_cases())
def case(request):
    name = request.param
    if not have(name):
        pytest.skip(f"no reference data for {name}")
    return name
