def build(name: str) -> dict:
    _, overrides = CASES[name]
    nml = copy.deepcopy(BASE)
    for override in overrides:
        nml = merge(nml, override)
    return nml


def main() -> None:
    readme = ["# GS2 JAX port: feature-matrix test cases", "",
              "Generated by `generate.py` (run it to rewrite the `.in` files).",
              "Each case is a complete GS2 input file; `gpu/scripts/make_refdata.sh`",
              "runs GS2 and the exporter on every case.", "",
              "| case | covers |", "|---|---|"]
    for name, (description, _) in CASES.items():
        (HERE / f"{name}.in").write_text(render(build(name)))
        readme.append(f"| `{name}` | {description} |")
    (HERE / "README.md").write_text("\n".join(readme) + "\n")
    print(f"wrote {len(CASES)} cases to {HERE}")


if __name__ == "__main__":
    main()
