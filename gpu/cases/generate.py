def _fmt(value) -> str:
    if isinstance(value, bool):
        return ".true." if value else ".false."
    if isinstance(value, str):
        return f'"{value}"'
    if isinstance(value, float):
        return repr(value)
    return str(value)


def render(namelists: dict[str, dict]) -> str:
    lines = ["! Generated by gpu/cases/generate.py -- do not edit by hand.", ""]
    for name, values in namelists.items():
        lines.append(f"&{name}")
        for key, value in values.items():
            lines.append(f" {key} = {_fmt(value)}")
        lines.append("/")
        lines.append("")
    return "\n".join(lines)


def merge(base: dict, overrides: dict) -> dict:
    """Merge namelist overrides; a value of None deletes the key, a namelist
    value of None deletes the whole namelist."""
    out = copy.deepcopy(base)
    for nml, values in overrides.items():
        if values is None:
            out.pop(nml, None)
            continue
        target = out.setdefault(nml, {})
        for key, value in values.items():
            if value is None:
                target.pop(key, None)
            else:
                target[key] = value
    return out


